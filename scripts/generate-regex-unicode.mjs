// Unicode 15.0 tables, generated exclusively from the pinned Unicode Consortium
// UCD inputs. Runtime matching does not invoke JavaScript's RegExp or casing.
import fs from 'node:fs';
import crypto from 'node:crypto';
const root = new URL('../fixtures/regex-unicode/', import.meta.url);
const names = ['UnicodeData.txt', 'Blocks.txt', 'SpecialCasing.txt'];
const input = Object.fromEntries(names.map(n => [n, fs.readFileSync(new URL(n, root), 'utf8')]));
const cats = new Array(0x110000).fill('Cn');
const lower = new Map(), upper = new Map();
let first;
for (const line of input['UnicodeData.txt'].trim().split(/\r?\n/)) {
  const f = line.split(';'), cp = parseInt(f[0], 16);
  if (f[1].endsWith(', First>')) { first = cp; continue; }
  if (f[1].endsWith(', Last>')) { cats.fill(f[2], first, cp + 1); continue; }
  cats[cp] = f[2];
  if (f[12]) upper.set(cp, f[12]);
  if (f[13]) lower.set(cp, f[13]);
}
for (const line of input['SpecialCasing.txt'].split(/\r?\n/)) {
  const fields = line.split('#')[0].trim().split(';').map(x => x.trim());
  if (fields.length < 5 || fields[4]) continue; // unconditional default Unicode mappings
  const cp = parseInt(fields[0], 16);
  lower.set(cp, fields[1]); upper.set(cp, fields[3]);
}
const canonical = s => s.split(' ').map(x => parseInt(x, 16)).join(',');
const candidates = new Set([...lower.keys(), ...upper.keys()]);
for (const m of [lower, upper]) for (const v of m.values()) {
  if (!v.includes(' ')) candidates.add(parseInt(v, 16));
}
const variants = new Map();
for (const mapping of [lower, upper]) {
  const inverse = new Map();
  for (const cp of candidates) {
    const key = canonical(mapping.get(cp) ?? cp.toString(16));
    if (!inverse.has(key)) inverse.set(key, []);
    inverse.get(key).push(cp);
  }
  for (const group of inverse.values()) if (group.length > 1) for (const cp of group) {
    if (!variants.has(cp)) variants.set(cp, new Set());
    for (const v of group) if (v !== cp) variants.get(cp).add(v);
  }
}
const ranges = [];
for (let a = 0; a < cats.length;) {
  let b = a + 1; while (b < cats.length && cats[b] === cats[a]) b++;
  ranges.push([a, b - 1, cats[a]]); a = b;
}
const blocks = [];
for (const line of input['Blocks.txt'].split(/\r?\n/)) {
  const m = /^([0-9A-F]+)\.\.([0-9A-F]+); (.+)$/.exec(line);
  if (m) blocks.push([m[3].replaceAll(' ', ''), parseInt(m[1], 16), parseInt(m[2], 16)]);
}
// Historical block spellings required by XML Schema 1.0 (Unicode 3.1).
for (const [old, current] of [['Greek','GreekandCoptic'], ['CombiningMarksforSymbols','CombiningDiacriticalMarksforSymbols'], ['PrivateUse','PrivateUseArea']]) {
  const b = blocks.find(x => x[0] === current); blocks.push([old, b[1], b[2]]);
}
const header = '// Generated by scripts/generate-regex-unicode.mjs. Unicode 15.0.0.\n// Derived Unicode data: see licenses/Unicode-DATA-LICENSE.txt.\n';
const out = header + '\n///|\nlet category_ranges : Array[(Int, Int, String)] = [\n' + ranges.map(([a,b,c]) => `  (${a}, ${b}, "${c}"),`).join('\n') + '\n]\n\n///|\nlet block_ranges : Map[String, (Int, Int)] = {\n' + blocks.map(([n,a,b]) => `  "${n}": (${a}, ${b}),`).join('\n') + '\n}\n\n///|\nlet case_variants : Map[Int, Array[Int]] = {\n' + [...variants].sort((a,b)=>a[0]-b[0]).map(([cp, v]) => `  ${cp}: [${[...v].sort((a,b)=>a-b).join(', ')}],`).join('\n') + '\n}\n';
fs.writeFileSync(new URL('../src/xpath_regex/unicode_generated.mbt', import.meta.url), out);
fs.writeFileSync(new URL('SOURCES.json', root), JSON.stringify({version:'15.0.0', license:'../../licenses/Unicode-DATA-LICENSE.txt', inputs:names.map(name => ({name, url:`https://www.unicode.org/Public/15.0.0/ucd/${name}`, sha256:crypto.createHash('sha256').update(fs.readFileSync(new URL(name, root))).digest('hex')})), generated:{categoryRanges:ranges.length, blocks:blocks.length, caseVariantCharacters:variants.size}}, null, 2)+'\n');
