function entities(s) {
  return s.replace(/&(#x[0-9a-f]+|#\d+|amp|lt|gt|apos|quot);/gi, (_, e) => e[0] === '#' ? String.fromCodePoint(parseInt(e[1] === 'x' ? e.slice(2) : e.slice(1), e[1] === 'x' ? 16 : 10)) : ({amp:'&',lt:'<',gt:'>',apos:"'",quot:'"'})[e]);
}
function text(s) { return s.startsWith('<![CDATA[') ? s.slice(9, -3) : entities(s); }
function parseExpression(s, xqueryEntities) {
  let pos = 0;
  const space = () => {while (/\s/.test(s[pos] ?? '') && pos < s.length) pos++;};
  function expr() {
    space();
    if (s[pos] === "'" || s[pos] === '"') {
      const quote = s[pos++]; let out = '';
      while (pos < s.length) {
        const c = s[pos++];
        if (c === quote) { if (s[pos] === quote) {out += s[pos++];} else return xqueryEntities ? entities(out) : out; }
        else out += c;
      }
      throw Error('unterminated literal');
    }
    const name = /^(?:fn:)?(matches|concat|codepoints-to-string)\s*\(/.exec(s.slice(pos));
    if (!name) throw Error('requires XPath evaluator or external environment');
    pos += name[0].length;
    if (name[1] === 'codepoints-to-string') {
      space(); const digits = /^\d+/.exec(s.slice(pos));
      if (!digits) throw Error('nonliteral codepoint'); pos += digits[0].length; space();
      if (s[pos++] !== ')') throw Error('complex codepoints');
      return String.fromCodePoint(Number(digits[0]));
    }
    const args = [];
    while (true) {
      args.push(expr()); space(); const close = s[pos++];
      if (close === ')') break;
      if (close !== ',') throw Error('argument syntax');
    }
    if (name[1] === 'concat') return args.join('');
    if (args.length !== 2 && args.length !== 3) throw Error('function arity test');
    return args;
  }
  const result = expr(); space();
  if (pos !== s.length || !Array.isArray(result)) throw Error('requires XPath evaluator');
  return result;
}
