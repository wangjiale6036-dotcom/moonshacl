  if (/<dependency type="xsd-version" value="1.1"/.test(body)) reason = 'XSD 1.1 grammar';
  const test = /<test>([\s\S]*?)<\/test>/.exec(body);
  const result = /<result>([\s\S]*?)<\/result>/.exec(body)?.[1] ?? '';
  let expected = /<assert-true\s*\/>/.test(result) ? true : /<assert-false\s*\/>/.test(result) ? false : /<error code="FORX000[12]"/.test(result) ? 'error' : /<assert-string-value>(true|false)<\/assert-string-value>/.exec(result)?.[1];
  if (expected === 'true') expected = true;
  if (expected === 'false') expected = false;
  if (/<any-of>/.test(result) && /<error code="FORX0002"/.test(result) && /<assert-false\s*\/>/.test(result)) expected = 'false-or-error';
